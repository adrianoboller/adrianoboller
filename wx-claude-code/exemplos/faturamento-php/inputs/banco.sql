-- Sistema FATURAMENTO - MySQL 5.7, latin1 na origem, migrado para utf8 em 2016.
-- Nomes de coluna em maiusculas por convencao da equipe original.

CREATE TABLE cliente (
  ID            INT AUTO_INCREMENT PRIMARY KEY,
  RAZAO_SOCIAL  VARCHAR(120) NOT NULL,
  CNPJ          VARCHAR(18)  NOT NULL,
  LIMITE        DECIMAL(12,2) NOT NULL DEFAULT 0,
  FORMA_PADRAO  CHAR(2) NOT NULL DEFAULT 'PZ',
  ATIVO         TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uk_cliente_cnpj (CNPJ)
) ENGINE=InnoDB;

CREATE TABLE pedido (
  ID          INT AUTO_INCREMENT PRIMARY KEY,
  ID_CLIENTE  INT NOT NULL,
  EMISSAO     DATE NOT NULL,
  SITUACAO    VARCHAR(12) NOT NULL DEFAULT 'A_FATURAR',
  CONSTRAINT fk_pedido_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES cliente(ID)
) ENGINE=InnoDB;

CREATE TABLE pedido_item (
  ID              INT AUTO_INCREMENT PRIMARY KEY,
  ID_PEDIDO       INT NOT NULL,
  DESCRICAO       VARCHAR(120) NOT NULL,
  QUANTIDADE      DECIMAL(12,3) NOT NULL,
  VALOR_UNITARIO  DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_item_pedido FOREIGN KEY (ID_PEDIDO) REFERENCES pedido(ID)
) ENGINE=InnoDB;

CREATE TABLE fatura (
  ID          INT AUTO_INCREMENT PRIMARY KEY,
  ID_CLIENTE  INT NOT NULL,
  EMISSAO     DATE NOT NULL,
  SUBTOTAL    DECIMAL(12,2) NOT NULL,
  DESCONTO    DECIMAL(12,2) NOT NULL DEFAULT 0,
  TOTAL       DECIMAL(12,2) NOT NULL,
  FORMA       CHAR(2) NOT NULL,
  CONSTRAINT fk_fatura_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES cliente(ID)
) ENGINE=InnoDB;

CREATE TABLE titulo (
  ID             INT AUTO_INCREMENT PRIMARY KEY,
  ID_FATURA      INT NOT NULL,
  ID_CLIENTE     INT NOT NULL,
  NUMERO         INT NOT NULL,
  VALOR          DECIMAL(12,2) NOT NULL,
  VENCIMENTO     DATE NOT NULL,
  SITUACAO       VARCHAR(10) NOT NULL DEFAULT 'ABERTO',
  DATA_PAGAMENTO DATE NULL,
  VALOR_MULTA    DECIMAL(12,2) NULL,
  VALOR_JUROS    DECIMAL(12,2) NULL,
  VALOR_PAGO     DECIMAL(12,2) NULL,
  KEY ix_titulo_venc (ID_CLIENTE, SITUACAO, VENCIMENTO),
  CONSTRAINT fk_titulo_fatura FOREIGN KEY (ID_FATURA) REFERENCES fatura(ID)
) ENGINE=InnoDB;

CREATE TABLE titulo_historico (
  ID        INT AUTO_INCREMENT PRIMARY KEY,
  ID_TITULO INT NOT NULL,
  EVENTO    VARCHAR(20) NOT NULL,
  QUANDO    DATETIME NOT NULL,
  CONSTRAINT fk_hist_titulo FOREIGN KEY (ID_TITULO) REFERENCES titulo(ID)
) ENGINE=InnoDB;

-- Usada pelo relatorio de inadimplencia (nao ha PHP que a chame; sobrou de
-- uma tela removida em 2018 - divergencia legitima para o G2 achar).
CREATE VIEW v_inadimplencia AS
SELECT c.ID, c.RAZAO_SOCIAL, MAX(DATEDIFF(CURDATE(), t.VENCIMENTO)) AS MAIOR_ATRASO,
       SUM(t.VALOR) AS EM_ABERTO
  FROM cliente c JOIN titulo t ON t.ID_CLIENTE = c.ID
 WHERE t.SITUACAO = 'ABERTO' AND t.VENCIMENTO < CURDATE()
 GROUP BY c.ID, c.RAZAO_SOCIAL;
