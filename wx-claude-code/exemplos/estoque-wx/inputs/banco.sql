CREATE TABLE CLIENTE (
  IDCLIENTE       INT NOT NULL AUTO_INCREMENT,
  NOME            VARCHAR(80) NOT NULL,
  CPF             CHAR(11) NOT NULL,
  EMAIL           VARCHAR(120),
  CIDADE          VARCHAR(60),
  UF              CHAR(2),
  TIPO            CHAR(1) NOT NULL DEFAULT 'C',   -- C = comum, E = especial
  LIMITE_CREDITO  DECIMAL(12,2) NOT NULL DEFAULT 0,
  ATIVO           BOOLEAN NOT NULL DEFAULT TRUE,
  DATA_CADASTRO   DATE NOT NULL,
  PRIMARY KEY (IDCLIENTE),
  UNIQUE KEY UK_CLIENTE_CPF (CPF)
);

CREATE TABLE PRODUTO (
  IDPRODUTO       INT NOT NULL AUTO_INCREMENT,
  CODIGO          VARCHAR(20) NOT NULL,
  DESCRICAO       VARCHAR(120) NOT NULL,
  UNIDADE         CHAR(2) NOT NULL DEFAULT 'UN',
  PRECO_VENDA     DECIMAL(12,2) NOT NULL,
  ESTOQUE_MINIMO  DECIMAL(12,3) NOT NULL DEFAULT 0,
  ATIVO           BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (IDPRODUTO),
  UNIQUE KEY UK_PRODUTO_CODIGO (CODIGO)
);

CREATE TABLE DEPOSITO (
  IDDEPOSITO      INT NOT NULL AUTO_INCREMENT,
  NOME            VARCHAR(40) NOT NULL,
  PRIMARY KEY (IDDEPOSITO)
);

CREATE TABLE SALDO (
  IDPRODUTO       INT NOT NULL,
  IDDEPOSITO      INT NOT NULL,
  QUANTIDADE      DECIMAL(12,3) NOT NULL DEFAULT 0,
  PRIMARY KEY (IDPRODUTO, IDDEPOSITO),
  CONSTRAINT FK_SALDO_PRODUTO  FOREIGN KEY (IDPRODUTO)  REFERENCES PRODUTO (IDPRODUTO),
  CONSTRAINT FK_SALDO_DEPOSITO FOREIGN KEY (IDDEPOSITO) REFERENCES DEPOSITO (IDDEPOSITO)
);

CREATE TABLE VENDA (
  IDVENDA         INT NOT NULL AUTO_INCREMENT,
  IDCLIENTE       INT NOT NULL,
  IDDEPOSITO      INT NOT NULL,
  DATA            DATE NOT NULL,
  VENDEDOR        VARCHAR(40) NOT NULL,
  SUBTOTAL        DECIMAL(12,2) NOT NULL DEFAULT 0,
  DESCONTO        DECIMAL(12,2) NOT NULL DEFAULT 0,
  TOTAL           DECIMAL(12,2) NOT NULL DEFAULT 0,
  STATUS          CHAR(1) NOT NULL DEFAULT 'A',   -- A = aberta, F = fechada, C = cancelada
  PRIMARY KEY (IDVENDA),
  KEY IX_VENDA_DATA (DATA),
  CONSTRAINT FK_VENDA_CLIENTE  FOREIGN KEY (IDCLIENTE)  REFERENCES CLIENTE (IDCLIENTE),
  CONSTRAINT FK_VENDA_DEPOSITO FOREIGN KEY (IDDEPOSITO) REFERENCES DEPOSITO (IDDEPOSITO)
);

CREATE TABLE ITEMVENDA (
  IDITEM          INT NOT NULL AUTO_INCREMENT,
  IDVENDA         INT NOT NULL,
  IDPRODUTO       INT NOT NULL,
  QUANTIDADE      DECIMAL(12,3) NOT NULL,
  PRECO_UNITARIO  DECIMAL(12,2) NOT NULL,
  TOTAL_ITEM      DECIMAL(12,2) NOT NULL,
  PRIMARY KEY (IDITEM),
  CONSTRAINT FK_ITEM_VENDA   FOREIGN KEY (IDVENDA)   REFERENCES VENDA (IDVENDA) ON DELETE CASCADE,
  CONSTRAINT FK_ITEM_PRODUTO FOREIGN KEY (IDPRODUTO) REFERENCES PRODUTO (IDPRODUTO)
);

CREATE TABLE TITULO (
  IDTITULO        INT NOT NULL AUTO_INCREMENT,
  IDVENDA         INT NOT NULL,
  VENCIMENTO      DATE NOT NULL,
  VALOR           DECIMAL(12,2) NOT NULL,
  PAGO_EM         DATE,
  VALOR_PAGO      DECIMAL(12,2),
  PRIMARY KEY (IDTITULO),
  CONSTRAINT FK_TITULO_VENDA FOREIGN KEY (IDVENDA) REFERENCES VENDA (IDVENDA)
);

CREATE VIEW VW_SALDO_ABAIXO_MINIMO AS
  SELECT P.CODIGO, P.DESCRICAO, D.NOME AS DEPOSITO, S.QUANTIDADE, P.ESTOQUE_MINIMO
    FROM SALDO S
    JOIN PRODUTO P ON P.IDPRODUTO = S.IDPRODUTO
    JOIN DEPOSITO D ON D.IDDEPOSITO = S.IDDEPOSITO
   WHERE S.QUANTIDADE < P.ESTOQUE_MINIMO;
