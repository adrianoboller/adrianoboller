-- DB-001: esquema de destino, traduzido de inputs/banco.sql (HFSQL Client/Server, exportado como MySQL).
-- O que mudou de dialeto, e por que: AUTO_INCREMENT -> GENERATED ALWAYS AS IDENTITY; BOOLEAN/DECIMAL iguais;
-- CHAR(1) STATUS ganha CHECK, porque o legado confiava na tela (A/F/C) e o banco nao conferia.
CREATE TABLE cliente (
  idcliente      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           VARCHAR(80) NOT NULL,
  cpf            CHAR(11) NOT NULL UNIQUE,
  email          VARCHAR(120),
  cidade         VARCHAR(60),
  uf             CHAR(2),
  tipo           CHAR(1) NOT NULL DEFAULT 'C' CHECK (tipo IN ('C','E')),
  limite_credito NUMERIC(12,2) NOT NULL DEFAULT 0,
  ativo          BOOLEAN NOT NULL DEFAULT TRUE,
  data_cadastro  DATE NOT NULL
);
CREATE TABLE produto (
  idproduto      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo         VARCHAR(20) NOT NULL UNIQUE,
  descricao      VARCHAR(120) NOT NULL,
  unidade        CHAR(2) NOT NULL DEFAULT 'UN',
  preco_venda    NUMERIC(12,2) NOT NULL,
  estoque_minimo NUMERIC(12,3) NOT NULL DEFAULT 0,
  ativo          BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE deposito (
  iddeposito     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           VARCHAR(40) NOT NULL
);
CREATE TABLE saldo (
  idproduto      INT NOT NULL REFERENCES produto (idproduto),
  iddeposito     INT NOT NULL REFERENCES deposito (iddeposito),
  quantidade     NUMERIC(12,3) NOT NULL DEFAULT 0,
  PRIMARY KEY (idproduto, iddeposito)
);
CREATE TABLE venda (
  idvenda        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idcliente      INT NOT NULL REFERENCES cliente (idcliente),
  iddeposito     INT NOT NULL REFERENCES deposito (iddeposito),
  data           DATE NOT NULL,
  vendedor       VARCHAR(40) NOT NULL,
  subtotal       NUMERIC(12,2) NOT NULL DEFAULT 0,
  desconto       NUMERIC(12,2) NOT NULL DEFAULT 0,
  total          NUMERIC(12,2) NOT NULL DEFAULT 0,
  status         CHAR(1) NOT NULL DEFAULT 'A' CHECK (status IN ('A','F','C'))
);
CREATE INDEX ix_venda_data ON venda (data);
CREATE TABLE itemvenda (
  iditem         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idvenda        INT NOT NULL REFERENCES venda (idvenda) ON DELETE CASCADE,
  idproduto      INT NOT NULL REFERENCES produto (idproduto),
  quantidade     NUMERIC(12,3) NOT NULL,
  preco_unitario NUMERIC(12,2) NOT NULL,
  total_item     NUMERIC(12,2) NOT NULL
);
CREATE TABLE titulo (
  idtitulo       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idvenda        INT NOT NULL REFERENCES venda (idvenda),
  vencimento     DATE NOT NULL,
  valor          NUMERIC(12,2) NOT NULL,
  pago_em        DATE,
  valor_pago     NUMERIC(12,2)
);
CREATE VIEW vw_saldo_abaixo_minimo AS
  SELECT p.codigo, p.descricao, d.nome AS deposito, s.quantidade, p.estoque_minimo
    FROM saldo s JOIN produto p ON p.idproduto = s.idproduto JOIN deposito d ON d.iddeposito = s.iddeposito
   WHERE s.quantidade < p.estoque_minimo;
